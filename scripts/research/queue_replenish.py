def _strategies(root: Path) -> Dict[str, Any]:
    return _yaml().safe_load((root / "config" / "strategies.yaml").read_text(encoding="utf-8"))["strategies"]


def repo_facts(root: Path) -> Dict[str, Any]:
    """The committed inputs the grids expand against. Read once, never inferred.
    Accounts come from the canonical loader (src.config.accounts_loader), never
    a hand-rolled parse."""
    from src.config.accounts_loader import load_accounts_dict
    strategies = _strategies(root)
    accounts = load_accounts_dict(root / "config" / "accounts.yaml")
    rostered = set()
    for acc in accounts.values():
        if isinstance(acc, dict):
            rostered.update(acc.get("strategies") or [])
    legs: Dict[str, Dict[str, Any]] = {}
    for leg in sorted(rostered):
        cfg = strategies.get(leg)
        if not isinstance(cfg, dict) or cfg.get("enabled") is False:
            continue
        if str(cfg.get("execution") or "live") != "live":
            continue
        syms = cfg.get("symbols") or []
        legs[leg] = {"symbol": str(syms[0]) if syms else "", "timeframe": str(cfg.get("timeframe") or "")}
    evidence: Dict[str, Dict[str, Any]] = {}
    for leg in legs:
        rec_path = root / "comms" / "strategy_evidence" / f"{leg}.json"
        if not rec_path.is_file():
            continue
        try:
            rec = json.loads(rec_path.read_text(encoding="utf-8"))
            src = root / str(rec["cost_stack"]["source"])
            rows = src.with_name(src.name.replace("__bt.json", "__trades.jsonl"))
            if not rows.is_file():
                continue
            n = sum(1 for ln in rows.open("r", encoding="utf-8") if ln.strip())
            evidence[leg] = {"trades_file": rows.relative_to(root).as_posix(), "n_trades": n}
        except (OSError, ValueError, KeyError, TypeError):
            continue
    from scripts.research.leg_corpus_s1 import money_families
    return {"legs": legs, "evidence": evidence, "money_families": sorted(money_families(root))}


